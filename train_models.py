"""Train both models, calculate all six metrics and save the results.

Run:  python train_models.py

Results are saved in:
  models/                      the trained models
  models/latest_evaluation.json  a backup copy of the results
  docs/results_summary.md      a table you can paste into the report / slides
  MongoDB (model_evaluations)  used by the dashboard
"""
from src.database import DatabaseError, get_db, save_evaluation
from src.preprocessing import PROJECT_FOLDER
from src.training import train_and_evaluate


def write_summary(e):
    lr, lg = e["linear_regression"], e["logistic_regression"]
    cm = lg["confusion_matrix"]
    text = f"""# Actual Evaluation Results (generated by train_models.py)

Dataset: {e['dataset']}
Training rows: {e['train_rows']} | Test rows: {e['test_rows']} | random_state: {e['random_state']}
Scores depend on the dataset and the train/test split.

## Logistic Regression (Pass/Fail) - positive class: {e['positive_class']}

| Metric | Value |
|---|---|
| Accuracy | {lg['accuracy']:.4f} |
| Precision | {lg['precision']:.4f} |
| Recall | {lg['recall']:.4f} |
| F1 Score | {lg['f1_score']:.4f} |

Confusion matrix (test set): TP={cm['true_positive']}, TN={cm['true_negative']}, FP={cm['false_positive']}, FN={cm['false_negative']}

## Linear Regression (Exam Marks)

| Metric | Value |
|---|---|
| R2 Score | {lr['r2_score']:.4f} |
| MAE (marks) | {lr['mae']:.4f} |
"""
    (PROJECT_FOLDER / "docs" / "results_summary.md").write_text(text)
    return text


def main():
    print("Training both models... (the same train/test split is used for both)")
    evaluation = train_and_evaluate()
    print(write_summary(evaluation))
    print("Models saved in the models/ folder.")

    try:
        db = get_db()
        save_evaluation(db, evaluation)
        print("Evaluation saved in MongoDB (collection: model_evaluations).")
    except DatabaseError as error:
        print(f"\nWARNING: results were NOT saved to MongoDB.\n{error}")
        print("The models and results file were still saved. Fix MongoDB, then run this script again.")


if __name__ == "__main__":
    main()
